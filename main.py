def build_report_text(situation_key):
    """生成纯文本报告（用于展示和导出）"""
    sit = SITUATIONS.get(situation_key)
    if not sit:
        return "未找到该情形。"
    lines = []
    lines.append(f"【情形编号】{situation_key}")
    lines.append(f"【情形名称】{sit['name']}")
    lines.append(f"【所属分类】{sit['type']}")
    lines.append(f"【适用条件】{sit['criteria']}")
    lines.append(f"【处罚主体路径】{sit['path']}")
    lines.append(f"【强制执行方式】{sit['enforcement']}")
    lines.append(f"【裁量适用】{sit['restriction']}")
    lines.append(f"【过渡期建议】{sit['transition']}")
    lines.append("")

    # 公告调查依据
    ann = sit["extra_sections"].get("公告调查依据", [])
    if ann:
        lines.append("【公告调查依据】")
        for k in ann:
            if k.startswith("（"):
                lines.append("  " + k)
            else:
                p = get_provision(k)
                if p:
                    lines.append(f"  · {p['law']}{p['article']}：{p['content']}")
        lines.append("")

    # 协助调查通知
    lines.append("【协助调查通知依据】")
    for k in DEFAULT_SECTIONS["协助调查通知依据"]:
        p = get_provision(k)
        if p:
            lines.append(f"  · {p['law']}{p['article']}：{p['content']}")
    lines.append("")

    # 处罚理由
    lines.append("【处罚理由（定性）】")
    for k in sit["legal_sections"].get("处罚理由", []):
        if k.startswith("（"):
            lines.append("  " + k)
            continue
        p = get_provision(k)
        if p:
            lines.append(f"  · {p['law']}{p['article']}：{p['content']}")
    lines.append("")

    # 处罚依据
    lines.append("【处罚依据（罚则）】")
    for k in sit["legal_sections"].get("处罚依据", []):
        p = get_provision(k)
        if p:
            lines.append(f"  · {p['law']}{p['article']}：{p['content']}")
    lines.append("")

    # 听证 / 申诉
    for sec in ("听证依据", "申诉依据"):
        lines.append(f"【{sec}】")
        for k in DEFAULT_SECTIONS[sec]:
            p = get_provision(k)
            if p:
                lines.append(f"  · {p['law']}{p['article']}：{p['content']}")
        lines.append("")

    # 查封（如适用）
    if situation_key not in NO_SEIZURE_SITUATIONS:
        for sec in ("查封依据", "延长查封期限依据"):
            lines.append(f"【{sec}】")
            for k in DEFAULT_SECTIONS[sec]:
                p = get_provision(k)
                if p:
                    lines.append(f"  · {p['law']}{p['article']}：{p['content']}")
            lines.append("")

    # 房产限制（如适用）
    if situation_key not in NO_PROPERTY_RESTRICTION_SITUATIONS:
        for sec in ("限制房产权利依据", "解除房产权利依据"):
            lines.append(f"【{sec}】")
            for k in DEFAULT_SECTIONS[sec]:
                p = get_provision(k)
                if p:
                    lines.append(f"  · {p['law']}{p['article']}：{p['content']}")
            lines.append("")

    # 移送依据
    move = sit["extra_sections"].get("移送依据", [])
    if move:
        lines.append("【移送依据】")
        for k in move:
            p = get_provision(k)
            if p:
                lines.append(f"  · {p['law']}{p['article']}：{p['content']}")
        lines.append("")

    # 裁量标准
    lines.append("【裁量标准】")
    for dk in sit["discretion_keys"]:
        std = DISCRETION_STANDARDS.get(dk)
        if std:
            lines.append(f"  ◆ {std['name']}")
            lines.append(f"    依据：{std['legal_basis']}")
            for cat in std["categories"]:
                lines.append(f"    ● {cat['title']}")
                for item in cat["items"]:
                    lines.append(f"      - 情形：{item['scene']}")
                    lines.append(f"        标准：{item['standard']}")
        else:
            kws = DISCRETION_KEYWORD_MAP.get(dk, [])
            lines.append(f"  ◆ 裁量键：{dk}")
            if kws:
                lines.append(f"    关键词：{'、'.join(kws)}（详见对应裁量基准文件）")
    lines.append("")
    lines.append("【备注】")
    lines.append("  1. 涉及重大执法决定的，应按《广东省重大行政执法决定法制审核办法》进行法制审核。")
    lines.append("  2. 本文书依据以现行有效法规为准，实际办案请核对原文。")
    return "\n".join(lines)


def search_provisions(keyword):
    """关键词搜索法条"""
    if not keyword:
        return []
    kw = keyword.strip()
    results = []
    all_p = dict(LEGAL_PROVISIONS)
    all_p.update(CSV_PROVISIONS)
    for k, v in all_p.items():
        if kw in v.get("law", "") or kw in v.get("article", "") or kw in v.get("content", ""):
            results.append((k, v))
    return results


def load_csv_file(path):
    """读取 CSV 法规库，写入 CSV_PROVISIONS"""
    count = 0
    try:
        with open(path, "r", encoding="utf-8-sig", errors="ignore") as f:
            reader = csv.DictReader(f)
            if not reader.fieldnames:
                return 0, "CSV 表头为空"
            headers = {h.strip(): h for h in reader.fieldnames}

            def pick(*names):
                for n in names:
                    for h in headers:
                        if n in h:
                            return headers[h]
                return None

            c_name = pick("名称", "标题", "文件名")
            c_no = pick("文号")
            c_body = pick("正文", "内容")
            c_art = pick("条")
            c_url = pick("网址", "链接")
            if not c_body:
                return 0, "CSV 缺少正文/内容列"
            for row in reader:
                body = (row.get(c_body) or "").strip()
                if not body:
                    continue
                name = (row.get(c_name) or "").strip() if c_name else ""
                key = f"{name}"
                if key and key not in CSV_PROVISIONS:
                    CSV_PROVISIONS[key] = {
                        "law": name or "（CSV）",
                        "article": row.get(c_art, "") if c_art else "",
                        "content": body[:800],
                        "url": row.get(c_url, "") if c_url else "",
                    }
                    count += 1
        return count, "OK"
    except Exception as e:
        return 0, f"读取失败：{e}"


